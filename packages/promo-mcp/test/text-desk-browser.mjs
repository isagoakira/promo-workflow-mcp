// Run explicitly with PROMO_PLAYWRIGHT_MODULE pointing at the installed Playwright module.
import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { ArtifactStore, JsonWorkflowStore, WorkspaceDeliverables, WorkflowService } from '@promo-workflow/service';
import { createReviewHost } from '../dist/review-host.js';

const { chromium }=await import(pathToFileURL(resolve(process.env.PROMO_PLAYWRIGHT_MODULE)));
const root=await mkdtemp(join(tmpdir(),'promo-text-browser-'));
const artifacts=new ArtifactStore(join(root,'artifacts')),store=new JsonWorkflowStore(join(root,'workflows.json'));
const oldText='刚上手工具时，你可能每天重复解释同一件事。🙂\n\n## 记忆在哪里\n打开记忆页面，看看刚保存的那条记录。\n\n这部分很长，需要压缩，同时保留核心体验。';
const old=await artifacts.write({kind:'content_master_draft',content:{master:{title:'一篇可审阅的文章',bodyMarkdown:oldText}}});
const newer=await artifacts.write({kind:'content_master_draft',content:{master:{title:'一篇可审阅的文章',bodyMarkdown:oldText.replace('这部分很长，需要压缩，同时保留核心体验。','只保留核心体验。')}},parentArtifactIds:[old.artifactId],revision:2});
const workspace=new WorkspaceDeliverables(join(root,'workspace'),artifacts);
const scope=workspace.scopeFor('wf-browser','article');
await workspace.sync({workflowId:'wf-browser',carrier:'article',displayName:'文字批注测试',rootDirectory:root,state:'ALIGNING_MASTER',revision:2,summary:'浏览器验收',artifactRefs:[old,newer],workspaceScope:scope});
await store.write({schemaVersion:1,workflows:{'wf-browser':{id:'wf-browser',carrier:'article',rootDirectory:root,displayName:'文字批注测试',state:'ALIGNING_MASTER',revision:2,createdAt:new Date().toISOString(),updatedAt:new Date().toISOString(),summary:'浏览器验收',context:{artifactRefs:[old,newer]},events:[],idempotency:{}}}});
const service=new WorkflowService(store,artifacts),server=createReviewHost({dataDirectory:root});
await new Promise(r=>server.listen(0,'127.0.0.1',r));const origin='http://127.0.0.1:'+server.address().port;
const browser=await chromium.launch({headless:true}),page=await browser.newPage({viewport:{width:1400,height:1000}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
try {
  await page.goto(origin+'/?workflowId=wf-browser');await page.waitForLoadState('networkidle');
  console.log('Discovered text controls:',await page.locator('[data-text-artifact]').count());
  await page.locator('[data-text-artifact]').first().click();
  await page.getByRole('dialog').waitFor();
  await page.getByLabel('文字版本').selectOption(old.artifactId);
  const select=async(start,end)=>page.locator('.text-field[data-field="/master/bodyMarkdown"]').evaluate((field,{start,end})=>{const r=document.createRange();r.setStart(field.firstChild,start);r.setEnd(field.firstChild,end);const s=window.getSelection();s.removeAllRanges();s.addRange(r);},{start,end});
  await select(3,oldText.indexOf('打开')+8);
  await page.getByRole('button',{name:'添加选区 / 追加片段',exact:true}).click();
  await select(oldText.indexOf('这部分'),oldText.length);
  await page.getByRole('button',{name:'添加选区 / 追加片段',exact:true}).click();
  assert.equal(await page.locator('.text-selected').count(),2);
  await page.getByLabel('批注意见').fill('太长了，保留记忆页面的核心体验。');
  await page.evaluate(()=>window.dispatchEvent(new Event('promo-text-update')));
  assert.equal(await page.getByLabel('批注意见').inputValue(),'太长了，保留记忆页面的核心体验。');
  assert.equal(await page.locator('.text-selected').count(),2);
  await page.getByRole('button',{name:'保存批注',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.text-status').textContent.includes('已保存'));
  let snapshot=await service.get('wf-browser');assert.equal(snapshot.reviewFeedback.pending.length,1);assert.equal(snapshot.reviewFeedback.pending[0].anchors.length,2);
  await page.getByRole('button',{name:'全文批注',exact:true}).click();
  await page.getByLabel('批注意见').fill('<img src=x onerror="alert(1)"> 第二条全文意见');
  await page.getByRole('button',{name:'保存批注',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('textarea').value==='');
  assert.equal(await page.locator('.text-note img').count(),0);
  await page.getByLabel('文字版本').selectOption(newer.artifactId);
  await page.getByRole('button',{name:'与上一版对比',exact:true}).click();
  assert.ok((await page.locator('.text-diff pre:nth-child(2)').allTextContents()).join('').includes('只保留核心体验'));
  assert.ok((await page.locator('.text-diff ins').allTextContents()).join('').includes('只'));
  await page.screenshot({path:join(root,'text-history.png'),fullPage:true});
  await page.getByRole('button',{name:'返回正文',exact:true}).click();
  await page.getByRole('button',{name:'定位原文',exact:true}).first().click();
  assert.equal(await page.getByLabel('文字版本').inputValue(),old.artifactId);
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  await page.reload();await page.waitForLoadState('networkidle');
  await page.locator('[data-text-artifact]').first().click();
  await page.locator('.text-note').first().waitFor();assert.equal(await page.locator('.text-note').count(),2);
  await page.getByLabel('批注意见').fill('网络失败也不要丢失这条意见。');
  await page.route('**/annotations',route=>route.abort(),{times:1});
  await page.getByRole('button',{name:'保存批注',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.text-status').textContent.includes('未保存'));
  assert.equal(await page.getByLabel('批注意见').inputValue(),'网络失败也不要丢失这条意见。');
  await page.getByRole('button',{name:'保存批注',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('textarea').value==='');
  assert.equal((await service.get('wf-browser')).reviewFeedback.pending.length,3);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,checks:['cross-paragraph selection','multiple ranges','multiple comments','draft survives update','durable next-turn feedback','XSS escaped','version diff','original anchor','reload persistence'],screenshot:join(root,'text-history.png')}));
} finally {await browser.close();await new Promise(r=>server.close(r));}
